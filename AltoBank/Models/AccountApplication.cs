using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace AltoBank.Models;

/// <summary>
/// Where an application is in review. With "Auto-approve applications" ON (the default) valid
/// applications are Approved instantly; with it OFF they wait as Pending until an admin approves or denies.
/// (Older data used "Declined"; the AdminPortal migration converts it to "Denied".)
/// </summary>
public enum ApplicationStatus
{
    Pending,
    Approved,
    Denied
}

/// <summary>
/// A submitted "open an account" application: a permanent record of what the customer
/// told us, linked to the user and to the Account it created.
/// NOTE: no real Social Security number is ever collected. SsnLast4 is 4 random digits
/// generated by the server to simulate an identity check.
/// </summary>
public class AccountApplication
{
    public int Id { get; set; }

    [Required]
    public string UserId { get; set; } = string.Empty;
    public ApplicationUser? User { get; set; }

    // The account this application opened (null if it was declined).
    public int? AccountId { get; set; }
    public Account? Account { get; set; }

    public ApplicationStatus Status { get; set; }
    public DateTime SubmittedAt { get; set; } = DateTime.UtcNow;

    // ----- Review (admin) -----
    public DateTime? ReviewedAt { get; set; }
    [StringLength(256)] public string? ReviewedBy { get; set; }
    // Shown to the customer when an application is denied.
    [StringLength(500)] public string? DenialReason { get; set; }

    // ----- Step 1: product -----
    public AccountType AccountType { get; set; }
    [StringLength(30)] public string? Nickname { get; set; }
    // Debit card design chosen in step 1 (checking). Stored so a pending application can be approved later.
    [StringLength(20)] public string? CardDesign { get; set; }

    // ----- Step 2: about you -----
    [Required, StringLength(50)] public string FirstName { get; set; } = string.Empty;
    [StringLength(1)] public string? MiddleInitial { get; set; }
    [Required, StringLength(50)] public string LastName { get; set; } = string.Empty;
    public DateOnly DateOfBirth { get; set; }
    [Required, StringLength(20)] public string Citizenship { get; set; } = string.Empty;

    // ----- Step 3: contact & address -----
    [Required, StringLength(256)] public string Email { get; set; } = string.Empty;
    [Required, StringLength(20)] public string Phone { get; set; } = string.Empty;
    [Required, StringLength(100)] public string Street { get; set; } = string.Empty;
    [StringLength(50)] public string? Apt { get; set; }
    [Required, StringLength(60)] public string City { get; set; } = string.Empty;
    [Required, StringLength(2)] public string State { get; set; } = string.Empty;
    [Required, StringLength(5)] public string Zip { get; set; } = string.Empty;
    public bool LivedAtAddressTwoYears { get; set; }
    [StringLength(100)] public string? PrevStreet { get; set; }
    [StringLength(60)] public string? PrevCity { get; set; }
    [StringLength(2)] public string? PrevState { get; set; }
    [StringLength(5)] public string? PrevZip { get; set; }

    // ----- Step 4: employment & income -----
    [Required, StringLength(30)] public string EmploymentStatus { get; set; } = string.Empty;
    [StringLength(80)] public string? Employer { get; set; }
    [StringLength(80)] public string? Occupation { get; set; }
    [Required, StringLength(40)] public string IncomeRange { get; set; } = string.Empty;
    [Required, StringLength(100)] public string SourceOfFunds { get; set; } = string.Empty; // comma-separated

    // ----- Step 5: simulated identity verification -----
    [Required, StringLength(4)] public string SsnLast4 { get; set; } = string.Empty;

    // ----- Step 6: funding -----
    [Column(TypeName = "decimal(18,2)")] public decimal OpeningDeposit { get; set; }
    [StringLength(100)] public string? FundingSource { get; set; }
    // Which Alto account funds the opening deposit (null = external bank, simulated).
    // Kept so an admin can approve a pending application later; funds are re-checked at approval time.
    public int? FundingAccountId { get; set; }

    // ----- Step 7: electronic signature -----
    [Required, StringLength(110)] public string ESignName { get; set; } = string.Empty;
    public DateTime ESignedAt { get; set; }
}
